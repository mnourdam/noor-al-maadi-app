export const REPORT_CONTROL_MESSAGES: Readonly<Record<AppLocale, ReportControlMessages>> = {
  ar,
  en,
  ur,
  id,
  tr,
  fr,
};
export function reportErrorCopy(locale: AppLocale, code?: string): string {
  const keys: readonly ReportReasonCode[] = [
    "auth_required",
    "cannot_report_own",
    "rate_limited",
    "not_found",
    "note_too_long",
  ];
  return REPORT_CONTROL_MESSAGES[locale][
    keys.includes(code as ReportReasonCode) ? (code as ReportReasonCode) : "unknown"
  ];
}

#!/usr/bin/env node
// ============================================================
// Story Cover Map generator (V16)
// ------------------------------------------------------------
// Emits a deterministic
//     story_id -> cover_media_id -> /story-media/<media_id>.webp
// mapping from the already-packaged Story Media Pack.
//
// Input : public/baseline-content.json  (published stories)
//         public/story-media/<media_id>.webp (packaged assets)
// Output: src/lib/stories/covers/cover-map.generated.ts
//
// No network. No secrets. Pure local derivation.
// ============================================================

import { readFileSync, existsSync, writeFileSync } from "node:fs";

const BASELINE = "public/baseline-content.json";
const MEDIA_DIR = "public/story-media";
const OUT = "src/lib/stories/covers/cover-map.generated.ts";

export function buildCoverMap(stories, hasAsset) {
  const mapped = {};
  const missing = [];
  const noCover = [];
  for (const s of stories) {
    const mediaId = s.cover_media_id ? String(s.cover_media_id) : "";
    if (!mediaId) {
      noCover.push(String(s.id));
      continue;
    }
    if (hasAsset(mediaId)) mapped[String(s.id)] = mediaId;
    else missing.push({ story_id: String(s.id), media_id: mediaId });
  }
  return { mapped, missing, noCover };
}

function main() {
  const baseline = JSON.parse(readFileSync(BASELINE, "utf8"));
  const stories = (baseline.collections?.stories ?? []).filter(
    (s) => s.status === "published" || s.status === undefined,
  );
  const { mapped, missing, noCover } = buildCoverMap(stories, (id) =>
    existsSync(`${MEDIA_DIR}/${id}.webp`),
  );

  const ids = Object.keys(mapped).sort();
  const body = ids.map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(mapped[id])},`).join("\n");

  writeFileSync(
    OUT,
    `// AUTO-GENERATED by scripts/generate-story-cover-map.mjs — do not edit by hand.
// story_id -> cover_media_id for every packaged cover in /story-media.
export const STORY_COVER_MEDIA_MAP: Readonly<Record<string, string>> = {
${body}
};

/** Stories that are published but have no authored cover (placeholder path). */
export const STORIES_WITHOUT_COVER: readonly string[] = [
${noCover
  .slice()
  .sort()
  .map((id) => `  ${JSON.stringify(id)},`)
  .join("\n")}
];
`,
    "utf8",
  );

  console.info(
    `[cover-map] ${ids.length} covers mapped, ${noCover.length} without authored cover, ${missing.length} missing packaged asset`,
  );
  if (missing.length) {
    for (const m of missing.slice(0, 20)) console.error(`[cover-map] MISSING ${m.story_id} -> ${m.media_id}`);
    process.exit(1);
  }
}

if (import.meta.url === `file://${process.argv[1]}`) main();
